import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync('apps/admin-web/src/features/inventory/inventoryQueryState.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const api = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const capabilities = { organization_read: true, branches: [{ id: 'a', name: 'Centro', timezone: 'America/Mazatlan' }, { id: 'b', name: 'Norte', timezone: 'America/Mazatlan' }] };
assert.deepEqual(api.initialInventoryScope(capabilities), { kind: 'organization', branch_id: null });
assert.equal(api.initialInventoryScope(undefined), null);
assert.deepEqual(api.initialInventoryScope({ ...capabilities, organization_read: false, branches: [capabilities.branches[1]] }), { kind: 'branch', branch_id: 'b' });
assert.equal(api.initialInventoryScope({ ...capabilities, organization_read: false }), null);
assert.equal(api.inventoryScopeAllowed(capabilities, { kind: 'branch', branch_id: 'foreign' }), false);
assert.equal(api.inventoryScopeAllowed({ ...capabilities, organization_read: false }, { kind: 'organization', branch_id: null }), false);
const original = { minimum_quantity: '12.345678', maximum_quantity: '20.000000' };
assert.deepEqual(api.thresholdPayload(original, {}, 3), { ...original, expected_version: 3 });
assert.equal(api.thresholdDraftError(original, { minimum: '12.345' }).includes('2 decimales'), true);
assert.equal(api.thresholdDraftError(original, { minimum: '21' }).length > 0, true);
assert.equal(api.thresholdDraftError(original, { minimum: '12.34' }), '');
assert.equal(api.thresholdDraftError(original, { minimum: '0', maximum: '0' }), '');
assert.deepEqual(api.thresholdPayload(original, { maximum: '25,50' }, 3), { minimum_quantity: '12.345678', maximum_quantity: '25.50', expected_version: 3 });
const stockSource = ts.createSourceFile('InventoryStock.tsx', readFileSync('apps/admin-web/src/features/inventory/InventoryStock.tsx', 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const dateFunction = stockSource.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'inventoryDate');
const dateCode = ts.transpileModule(ts.createPrinter().printNode(ts.EmitHint.Unspecified, dateFunction, stockSource), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { inventoryDate } = await import(`data:text/javascript;base64,${Buffer.from(dateCode).toString('base64')}`);
assert.match(inventoryDate('2026-01-02T00:00:00Z', 'America/New_York'), /(?:7:00|19:00)/);
assert.match(inventoryDate('2026-07-02T00:00:00Z', 'America/New_York'), /(?:8:00|20:00)/);
assert.match(inventoryDate('2026-01-02T00:00:00Z', 'UTC'), /UTC$/);
assert.equal(inventoryDate(null, 'UTC'), 'Sin movimientos');
assert.equal(inventoryDate('invalid', 'UTC'), 'Fecha no disponible');
console.log('Inventory scope and exact threshold edits verified');
