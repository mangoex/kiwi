console.log('Closed cash parsers reject money, foreign scopes, stale policy and mismatched receipts');
const intents = await load('apps/pos-web/src/features/settings/cashShiftIntent.ts');
const values = new Map();
globalThis.sessionStorage = {getItem:k => values.get(k) ?? null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
const scope = {organization:'org',actor:'cashier',branch:'a',register:'Caja 1'};
const command = {action:'open',key:'stable-key',payload:{branch_id:'a',register_id:'Caja 1',opening_cash_cents:50000}};
intents.saveShiftIntent(scope,command);
assert.deepEqual(intents.loadShiftIntent(scope),command,'Remount recovers exact key and body');
assert.equal(intents.loadShiftIntent({...scope,actor:'other'}),null);
assert.equal(intents.loadShiftIntent({...scope,branch:'b'}),null);
assert.throws(() => intents.saveShiftIntent(scope,{...command,key:'replacement'}));
assert.deepEqual(intents.loadShiftIntent(scope),command,'Uncertain command is never overwritten');
intents.clearShiftIntent(scope,'other-key');
assert.deepEqual(intents.loadShiftIntent(scope),command);
intents.clearShiftIntent(scope,command.key);
assert.equal(intents.loadShiftIntent(scope),null);
assert.throws(() => intents.saveShiftIntent(scope,{...command,payload:{...command.payload,branch_id:'b'}}));
intents.saveShiftIntent(scope,command);
const storageKey = [...values.keys()][0];values.set(storageKey,'{corrupt');
assert.throws(() => intents.loadShiftIntent(scope));assert.equal(values.get(storageKey),'{corrupt');
