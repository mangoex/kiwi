assert.equal(cuts.userCashCutCapabilities([], active).read, true, 'Operational read must not require legacy financial read');
assert.equal(cuts.userCashCutCapabilities(['cash.user_cut.create','cash.user_cut.read'], active).create, false, 'Phase 2 capture is not available');
